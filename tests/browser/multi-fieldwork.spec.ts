import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('three selected nests send one shared order and selection survives zoom', async ({ page }) => {
  await page.goto('/'); await page.getByRole('button', { name: 'Start match', exact: true }).click();
  await page.getByRole('button', { name: 'Skip tutorial' }).click();
  await page.evaluate(() => { const s = window.__supercolony.getState(); s.aiEnabled = false; ['california-0', 'california-1', 'california-3'].forEach(id => { const n = s.nodes.find(n => n.id === id)!; n.owner = 'player'; n.units = 80; }); window.__supercolony.advance(.1); });
    await page.getByRole('button', { name: /Choose sources/ }).click();
  await page.getByRole('checkbox', { name: /Garden edge · California/ }).check();
  await page.getByRole('checkbox', { name: /Shaded grove · California/ }).check();
  await page.getByRole('button', { name: 'Use selected nests' }).click();
  await expect(page.getByText('3 nests selected', { exact: true })).toBeVisible();
  await page.getByText('Keyboard orders', { exact: true }).click();
  await page.getByLabel('Destination nest').selectOption('california-4');
  await page.getByRole('button', { name: 'Send swarms', exact: true }).click();
  expect(await page.evaluate(() => window.__supercolony.getState().fleets.filter(f => f.owner === 'player').length)).toBe(3);
  await page.getByRole('button', { name: 'Pause match' }).click();
  await page.getByRole('button', { name: 'Zoom into California', exact: true }).click();
  await expect(page.locator('.map-node.player[aria-pressed="true"]')).toHaveCount(3);
  await page.getByRole('button', { name: 'World view', exact: true }).click();
  await expect(page.getByText('3 nests selected', { exact: true })).toBeVisible();
});
test('guided fieldwork reveals observations, tests a response, and records a follow-up', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/'); await page.getByRole('button', { name: 'Ecologist', exact: true }).click();
  await page.getByRole('button', { name: 'Start match', exact: true }).click(); await page.getByRole('button', { name: 'Skip tutorial' }).click();
  await page.getByRole('button', { name: 'Nest details', exact: true }).click();
  await page.getByRole('button', { name: 'Observe local trails', exact: true }).click();
  await page.getByRole('button', { name: 'Pause fieldwork', exact: true }).click();
  await page.evaluate(() => window.__supercolony.advance(10));
  await expect(page.getByText('Survey in progress', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Resume fieldwork', exact: true }).click();
  await page.evaluate(() => window.__supercolony.advance(4));
  await expect(page.getByRole('heading', { name: 'Your observation' })).toBeVisible();
  await page.getByRole('button', { name: 'Improve habitat', exact: true }).click();
  await page.getByRole('button', { name: 'Restore habitat', exact: true }).click();
  expect(await page.evaluate(() => window.__supercolony.getState().charges)).toBe(2);
  await expect(page.getByRole('button', { name: 'Record follow-up' })).toBeDisabled();
  await page.evaluate(() => window.__supercolony.advance(11));
  await page.getByRole('button', { name: 'Record follow-up' }).click();
  await expect(page.getByRole('heading', { name: 'What changed?' })).toBeVisible();
  await expect(page.getByText(/Habitat score/).last()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const audit = await new AxeBuilder({ page }).analyze(); expect(audit.violations).toEqual([]);
});
